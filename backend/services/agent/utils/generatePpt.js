import pptxgen from "pptxgenjs";

const COLORS = {
  primary: "2563EB",
  secondary: "0F172A",
  text: "334155",
  light: "F8FAFC",
  border: "E2E8F0",
  white: "FFFFFF",
  muted: "647488",
};

// LAYOUT_WIDE is 13.33 x 7.5 inches; content stays inside 0.7in side margins.
const MARGIN = 0.7;
const CONTENT_WIDTH = 13.33 - MARGIN * 2;

export const generatePpt = async (data) => {
  const ppt = new pptxgen();
  ppt.layout = "LAYOUT_WIDE";
  ppt.author = "AtlasAI";
  ppt.title = data.title;
  ppt.subject = data.title;
  ppt.company = "AtlasAI";
  ppt.lang = "en-US";
  ppt.theme = {
    headFontFace: "Aptos",
    bodyFontFace: "Aptos",
  };

  addCover(ppt, data);
  data.slides?.forEach((s, i) => {
    addContentSlide(ppt, s.title, s.points, i + 1, data.slides.length);
  });
  addThankYou(ppt);
  return ppt;
};

const addCover = (ppt, data) => {
  const slide = ppt.addSlide();
  slide.background = {
    color: COLORS.primary,
  };

  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.18,
    fill: {
      color: "60A5FA",
    },
    line: {
      color: "60A5FA",
    },
  });

  slide.addText(data.title || "Presentation", {
    x: 0.7,
    y: 2.3,
    w: 12,
    h: 1.2,
    align: "center",
    valign: "middle",
    color: COLORS.white,
    bold: true,
    fontSize: 40,
    fit: "shrink",
  });

  // addText() fails on undefined, and the model does not always send a subtitle.
  slide.addText(data.subtitle || "", {
    x: 1,
    y: 3.6,
    w: 11.5,
    h: 0.6,
    align: "center",
    color: "DBEAFE",
    fontSize: 18,
    fit: "shrink",
  });

  slide.addText("Generated by AtlasAI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "center",
    color: "BFDBFE",
    fontSize: 10,
  });
};

const addContentSlide = (ppt, title, points, page, total) => {
  const slide = ppt.addSlide();
  slide.background = {
    color: COLORS.white,
  };

  // The title is the slide's own title (it used to read an undefined `data`).
  slide.addText(title || `Slide ${page}`, {
    x: MARGIN,
    y: 0.35,
    w: CONTENT_WIDTH,
    h: 0.5,
    align: "center",
    color: COLORS.primary,
    bold: true,
    fontSize: 24,
    fit: "shrink",
  });

  // Accent bar along the top edge (a `line` shape with a height drew a diagonal).
  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.18,
    fill: {
      color: COLORS.primary,
    },
    line: {
      color: COLORS.primary,
    },
  });

  const visiblePoints = (Array.isArray(points) ? points : []).slice(0, 6);

  visiblePoints.forEach((point, index) => {
    const y = 1.2 + index * 0.75;

    // One tinted row per bullet; it was 13.33in wide and 0.18in tall before.
    slide.addShape(ppt.ShapeType.roundRect, {
      x: MARGIN,
      y,
      w: CONTENT_WIDTH,
      h: 0.62,
      fill: {
        color: index % 2 ? "F8FAFC" : "EFF6FF",
      },
      line: {
        color: COLORS.border,
      },
      rectRadius: 0.08,
    });

    slide.addShape(ppt.ShapeType.ellipse, {
      x: MARGIN + 0.25,
      y: y + 0.25,
      w: 0.12,
      h: 0.12,
      fill: {
        color: COLORS.primary,
      },
      line: {
        color: COLORS.primary,
      },
    });

    slide.addText(String(point), {
      x: MARGIN + 0.55,
      y,
      w: CONTENT_WIDTH - 0.8,
      h: 0.62,
      valign: "middle",
      fontSize: 15,
      color: COLORS.text,
      fit: "shrink",
    });
  });

  slide.addText(`${page} / ${total}`, {
    x: 12.1,
    y: 6.9,
    w: 0.8,
    h: 0.2,
    align: "right",
    fontSize: 10,
    color: COLORS.muted,
  });

  slide.addText("AtlasAI", {
    x: 0.6,
    y: 6.9,
    w: 2,
    h: 0.2,
    fontSize: 10,
    color: COLORS.muted,
  });
};

const addThankYou = (ppt) => {
  const slide = ppt.addSlide();
  slide.background = {
    color: COLORS.secondary,
  };

  slide.addText("Thank you", {
    x: 0,
    y: 2.2,
    w: 13.33,
    h: 0.8,
    align: "center",
    color: COLORS.white,
    bold: true,
    fontSize: 36,
  });

  slide.addText("Generated by AtlasAI", {
    x: 0,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "center",
    color: "94A3B8",
    fontSize: 10,
  });
};